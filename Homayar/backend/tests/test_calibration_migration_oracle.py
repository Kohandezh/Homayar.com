def _names(target, constraint: str) -> str:
    if not target.postgres:
        if constraint in SQLITE_UNIQUE:
            table, columns = SQLITE_UNIQUE[constraint]
            return re.escape(", ".join(f"{table}.{column}" for column in columns))
        if constraint.startswith("fk_"):
            return "FOREIGN KEY constraint failed"
    return rf"\b{constraint}\b"


def _deny(target, name: str, values: dict[str, object], constraint: str, *also: str) -> None:
    names = (constraint, *also) if target.postgres else (constraint,)
    target.refuse(
        insert(target.table(name)).values(values),
        "|".join(_names(target, each) for each in names),
    )


def _deny_null(target, name: str, values: dict[str, object], column: str) -> None:
    target.refuse(
        insert(target.table(name)).values(values),
        rf"{name}\.{column}\b|null value in column \"{column}\"",
    )


def _deny_long_title(target, title: str) -> None:
    statement = insert(target.table(BATCHES)).values(_batch(target, title=title))
    if target.postgres:
        target.refuse(
            statement,
            rf"\b{TITLE_CHECK}\b|value too long for type character varying",
            (IntegrityError, DataError),
        )
    else:
        target.refuse(statement, rf"\b{TITLE_CHECK}\b")


def _allow(target, name: str, values: dict[str, object]) -> str:
    target.run(insert(target.table(name)).values(values))
    return str(values["id"])


def _new_batch(target, **extra: object) -> str:
    return _allow(target, BATCHES, _batch(target, **extra))


def _slot(target, **example: object) -> dict[str, str]:
    batch_id = _new_batch(target)
    values = _example(target, batch_id, **example)
    example_id = _allow(target, EXAMPLES, values)
    participant_id = _allow(target, PARTICIPANTS, _participant(target, batch_id))
    return {
        "batch_id": batch_id,
        "example_id": example_id,
        "participant_id": participant_id,
        "meeting_id": str(values["meeting_id"]),
        "result_id": str(values["scorecard_result_id"]),
    }


def _assert_title_rules(target) -> None:
    for title in ("", "   "):
        _deny(target, BATCHES, _batch(target, title=title), TITLE_CHECK)
    for title in ("x" * (TITLE_MAX + 1), "ن" * (TITLE_MAX + 1)):
        _deny_long_title(target, title)
    _deny_null(target, BATCHES, _batch(target, title=None), "title")
    for title in ("x", "x" * TITLE_MAX, "ن" * TITLE_MAX, "  x  "):
        _allow(target, BATCHES, _batch(target, title=title))


