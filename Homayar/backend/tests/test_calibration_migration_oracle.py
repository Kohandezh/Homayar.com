@pytest.mark.postgres
def test_the_app_role_updates_every_calibration_table_but_the_examples(client, email_outbox):
    _requires_postgres()
    full = {"SELECT": True, "INSERT": True, "UPDATE": True, "DELETE": True}
    expected = {name: full for name in TABLES} | {EXAMPLES: {**full, "UPDATE": False}}
    assert {name: _privileges(name) for name in TABLES} == expected
    _apply_as_owner()
    assert {name: _privileges(name) for name in TABLES} == expected

    first = _Database(_tenant(client, email_outbox, "grants-a"), "grants")
    second = _Database(_tenant(client, email_outbox, "grants-b"), "grants")
    ours = dict(_rows(first))
    theirs = dict(_rows(second))
    for rows, target in ((ours, first), (theirs, second)):
        for name, values in rows.items():
            _allow(target, name, values)
    factory = get_session_factory()

    for name, change in UPDATES.items():
        table = _table(name)
        with factory() as db:
            assert db.scalar(text("SELECT current_user")) == APP_ROLE
            bind_tenant_context(db, workspace_id=first.workspace_id)
            changed = db.execute(
                update(table)
                .where(table.c.id.in_([ours[name]["id"], theirs[name]["id"]]))
                .values(**change)
            )
            assert changed.rowcount == 1, name
            db.commit()
        for column, value in change.items():
            assert _snapshot(name, str(ours[name]["id"]))[column] == value, name
            assert _snapshot(name, str(theirs[name]["id"]))[column] == theirs[name][column], name

    table = _table(EXAMPLES)
    with factory() as db:
        bind_tenant_context(db, workspace_id=first.workspace_id)
        with pytest.raises(DBAPIError, match="permission denied"):
            db.execute(update(table).where(table.c.id == ours[EXAMPLES]["id"]).values(position=1))
        db.rollback()
    with factory() as db:
        bind_tenant_context(db, workspace_id=first.workspace_id)
        assert db.execute(delete(table).where(table.c.id == theirs[EXAMPLES]["id"])).rowcount == 0
        assert db.execute(delete(table).where(table.c.id == ours[EXAMPLES]["id"])).rowcount == 1
        db.commit()
    assert _ids(EXAMPLES) == {theirs[EXAMPLES]["id"]}
    assert _count(ANSWERS, workspace_id=first.workspace_id) == 0
    assert _count(ADJUDICATIONS, workspace_id=first.workspace_id) == 0
    assert _count(ANSWERS, workspace_id=second.workspace_id) == 1
