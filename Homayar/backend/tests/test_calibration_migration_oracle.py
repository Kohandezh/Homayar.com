@pytest.mark.postgres
def test_a_session_reads_and_writes_only_its_own_workspace_rows(client, email_outbox):
    _requires_postgres()
    first = _Database(_tenant(client, email_outbox, "tenant-a"), "tenant")
    second = _Database(_tenant(client, email_outbox, "tenant-b"), "tenant")
    a, b = first.workspace_id, second.workspace_id
    factory = get_session_factory()

    with factory() as db:
        assert db.scalar(text("SELECT current_user")) == APP_ROLE
        bind_tenant_context(db, workspace_id=a)
        for name, values in _rows(first):
            db.execute(insert(_table(name)).values(values))
        db.commit()

    with factory() as db:
        bind_tenant_context(db, workspace_id=b)
        for name in TABLES:
            table = _table(name)
            assert db.execute(select(table.c.id)).all() == [], name
            assert db.execute(select(table.c.id).where(table.c.workspace_id == a)).all() == [], name
        for name, values in _rows(second):
            db.execute(insert(_table(name)).values(values))
        db.commit()

    with factory() as db:
        bind_tenant_context(db, workspace_id=a)
        for name in TABLES:
            assert list(db.execute(select(_table(name).c.workspace_id)).scalars()) == [a], name

    for name, values in _rows(second):
        with factory() as db:
            bind_tenant_context(db, workspace_id=a)
            with pytest.raises(DBAPIError, match="row-level security"):
                db.execute(insert(_table(name)).values(values))
            db.rollback()
        _allow(second, name, values)

    with factory() as db:
        bind_tenant_context(db, workspace_id=a)
        for name, values in _rows(first):
            db.execute(insert(_table(name)).values(values))
        db.commit()

    with factory() as db:
        for name in TABLES:
            assert db.execute(select(_table(name).c.id)).all() == [], name

    for name in TABLES:
        assert (_count(name, workspace_id=a), _count(name, workspace_id=b)) == (2, 2), name


