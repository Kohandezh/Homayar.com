def _names(target, constraint: str) -> str:
    if not target.postgres:
        if constraint == ACTIVE_UNIQUE:
            return re.escape(", ".join(f"{TABLE}.{column}" for column in ACTIVE_COLUMNS))
        if constraint.startswith("fk_"):
            return "FOREIGN KEY constraint failed"
    return rf"\b{constraint}\b"


def _deny(target, values: dict[str, object], constraint: str, *also: str) -> None:
    names = (constraint, *also) if target.postgres else (constraint,)
    target.refuse(
        insert(target.table()).values(values),
        "|".join(_names(target, each) for each in names),
    )


def _deny_null(target, values: dict[str, object], column: str) -> None:
    target.refuse(
        insert(target.table()).values(values),
        rf"{TABLE}\.{column}\b|null value in column \"{column}\"",
    )


def _allow(target, values: dict[str, object]) -> str:
    target.run(insert(target.table()).values(values))
    return str(values["id"])


def _assert_status_rules(target) -> None:
    spare = target.reviewed()
    for status in (
        "open",
        "Assigned",
        "ASSIGNED",
        "assigned ",
        " assigned",
        "canceled",
        "acknowledge",
        "done",
        "",
    ):
        _deny(target, _task(target, spare, status=status), STATUS_CHECK)
    _deny_null(target, _task(target, spare, status=None), "status")
    for build in (_task, _acknowledged, _closed, _cancelled):
        _allow(target, build(target, target.reviewed()))


def _assert_revision_rules(target) -> None:
    spare = target.reviewed()
