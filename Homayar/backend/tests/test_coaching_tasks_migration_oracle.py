class _Database:
    def __init__(self, tenant: dict, key: str, meeting_id: str | None = None) -> None:
        self.postgres = _on_postgres()
        self.workspace_id = tenant["workspace_id"]
        self.user_id = tenant["user_id"]
        self.parents = _parents(tenant, key=key, meeting_id=meeting_id)
        self.meeting_id = self.parents["meeting_id"]
        self.result_id = self.scored()

    def table(self) -> Table:
        return _table()

    def scored(self, *extra: str) -> str:
        rows = [(CRITERIA[outcome], MACHINE_FIELDS[outcome]) for outcome in MACHINE_VALUES]
        rows += [(criterion_id, MACHINE_FIELDS["passed"]) for criterion_id in extra]
        with inspection_session_factory()() as db:
            result = ScorecardResultRecord(**_result(self.parents))
            db.add(result)
            db.flush()
            for position, (criterion_id, fields) in enumerate(rows):
                db.add(
                    CriterionResultRecord(
                        **_criterion(
                            self.parents, result.id, position, criterion_id=criterion_id, **fields
                        )
                    )
                )
            db.commit()
            return result.id

    def meeting(self) -> str:
        with inspection_session_factory()() as db:
            meeting = Meeting(
                workspace_id=self.workspace_id, created_by_user_id=self.user_id, title="Other call"
            )
            db.add(meeting)
            db.commit()
            return meeting.id

    def item(self, result_id: str | None = None) -> str:
        values = _item_values(self, result_id or self.result_id)
        self.run(insert(_table(ITEMS)).values(values))
        return str(values["id"])

    def reviewed(self, result_id: str | None = None) -> str:
        result_id = result_id or self.result_id
        item_id = self.item(result_id)
        self.run(insert(_table(HUMAN)).values(_human(self, item_id, scorecard_result_id=result_id)))
        return item_id

    def run(self, statement) -> None:
        with inspection_session_factory()() as db:
            db.execute(statement)
            db.commit()

    def refuse(self, statement, pattern: str) -> None:
        with inspection_session_factory()() as db:
            with pytest.raises(IntegrityError, match=pattern):
                db.execute(statement)
            db.rollback()


