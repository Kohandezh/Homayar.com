def _deref(node, root):
    while isinstance(node, dict) and "$ref" in node:
        reference = node["$ref"]
        assert reference.startswith("#/"), reference
        target = root
        for part in reference[2:].split("/"):
            target = target[part]
        node = target
    return node


def _types(node, root) -> set:
    node = _deref(node, root)
    if "anyOf" in node:
        return set().union(*(_types(option, root) for option in node["anyOf"]))
    kind = node.get("type")
    return set(kind) if isinstance(kind, list) else {kind}


def _enum(node, root) -> list:
    node = _deref(node, root)
    if "anyOf" in node:
        return [item for option in node["anyOf"] for item in _enum(option, root)]
    return list(node.get("enum", []))


def _object(node, root) -> dict:
    node = _deref(node, root)
    assert _types(node, root) == {"object"}, node
    return node


def _value_schema(schema: dict, dimension: str) -> dict:
    extraction = _object(schema["properties"]["extraction"], schema)
    field = _object(extraction["properties"][dimension], schema)
    values = _deref(field["properties"]["values"], schema)
    assert _types(values, schema) == {"array"}, values
    return _object(values["items"], schema)


def _object_nodes(node, root, found: list) -> list:
    node = _deref(node, root)
    if not isinstance(node, dict):
        return found
    if "object" in _types(node, root):
        found.append(node)
    for child in node.get("properties", {}).values():
        _object_nodes(child, root, found)
    if "items" in node:
        _object_nodes(node["items"], root, found)
    for option in node.get("anyOf", []):
        _object_nodes(option, root, found)
    return found


