RECORD_KEYS = set(vars(logging.makeLogRecord({}))) | {"message", "asctime"}


def _record_text(record: logging.LogRecord) -> str:
    extra = {key: value for key, value in vars(record).items() if key not in RECORD_KEYS}
    return record.getMessage() + " " + json.dumps(extra, ensure_ascii=False, default=str)


def _missing_warnings(caplog) -> list[tuple[logging.LogRecord, str]]:
    found = []
    for record in caplog.records:
        body = _record_text(record)
        if record.levelno == logging.WARNING and "missing_from_output" in body:
            found.append((record, body))
    return found


