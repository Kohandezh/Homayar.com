@pytest.mark.postgres
def test_a_fresh_database_upgrades_through_the_new_revision_and_back(settings, alembic_config):
    reset_postgres_schema(settings.database_url)
    try:
        command.upgrade(alembic_config, BASE_HEAD)
        assert _table_exists() is False
        assert "'extraction'" not in _finding_check()
        command.upgrade(alembic_config, "head")
        assert _table_exists() is True
        assert _rls_posture() == (True, True)
        assert "'extraction'" in _finding_check()
        try:
            command.check(alembic_config)
        except AutogenerateDiffsDetected as exc:
            pytest.fail(f"the migration does not match the models: {exc}")
        command.downgrade(alembic_config, BASE_HEAD)
        assert _table_exists() is False
        command.upgrade(alembic_config, "head")
        assert _table_exists() is True
        assert _version() == _new_head() != BASE_HEAD
    finally:
        reset_postgres_schema(settings.database_url)
