def _counted(node):
    if isinstance(node, dict):
        return {
            key: len(value) if key == "evidence_ids" else _counted(value)
            for key, value in node.items()
        }
    if isinstance(node, list):
        return [_counted(item) for item in node]
    return node


def _analysis_content(meeting_id: str) -> dict:
    run = _current_run(meeting_id)
    with inspection_session_factory()() as db:
        summary = db.scalar(
            select(saas_models.MeetingSummary).where(
                saas_models.MeetingSummary.meeting_id == meeting_id
            )
        )
        actions = db.scalars(
            select(saas_models.ActionItem).where(saas_models.ActionItem.meeting_id == meeting_id)
        ).all()
        spans = db.execute(
            select(
                EvidenceSpan.finding_type,
                EvidenceSpan.finding_index,
                EvidenceSpan.finding_id,
                TranscriptSegment.sequence,
                EvidenceSpan.confidence,
            )
            .join(TranscriptSegment, TranscriptSegment.id == EvidenceSpan.segment_id)
            .where(
                EvidenceSpan.analysis_run_id == run.id,
                EvidenceSpan.finding_type != "extraction",
            )
        ).all()
    described = {action.id: action.description for action in actions}
    return {
        "state": run.state,
        "overview": summary.overview,
        "key_points": _counted(summary.key_points),
        "decisions": _counted(summary.decisions),
        "topics": summary.topics,
        "evidence_status": summary.evidence_status,
        "actions": sorted(
            (action.description, action.evidence_status, action.created_by) for action in actions
        ),
        "spans": sorted(
            (
                (kind, index, described.get(finding, finding), sequence, confidence)
                for kind, index, finding, sequence, confidence in spans
            ),
            key=repr,
        ),
    }


