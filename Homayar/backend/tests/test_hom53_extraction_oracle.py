def _spans(run_id: str) -> list[tuple[int, int, float]]:
    with inspection_session_factory()() as db:
        found = db.execute(
            select(EvidenceSpan.finding_index, TranscriptSegment.sequence, EvidenceSpan.confidence)
            .join(TranscriptSegment, TranscriptSegment.id == EvidenceSpan.segment_id)
            .where(
                EvidenceSpan.analysis_run_id == run_id,
                EvidenceSpan.finding_type == "extraction",
            )
        ).all()
    return sorted((index, sequence, confidence) for index, sequence, confidence in found)


def _kept_spans(result: dict) -> list[tuple[int, int, float]]:
    spans = []
    position = 0
    for name in DIMENSIONS:
        for value in result["fields"][name]["values"]:
            for index in dict.fromkeys(value["source_turn_indexes"]):
                spans.append((position, index, value["confidence"]))
            position += 1
    return sorted(spans)


