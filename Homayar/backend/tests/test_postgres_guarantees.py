"""PostgreSQL-only guarantees (WP01-T05).

These tests are skipped on the SQLite fallback because SQLite silently ignores
``SELECT ... FOR UPDATE`` and cannot validate the Alembic migration chain the
way production PostgreSQL does.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import select, text

from backend.config import Settings, reset_settings_cache
from backend.database.saas_models import JobState, ProcessingJob
from backend.jobs.processor import _claim_job
from backend.tests._database import inspection_session_factory, reset_postgres_schema
from backend.tests.test_job_processor import _queued_upload

pytestmark = pytest.mark.postgres

REPO_ROOT = Path(__file__).resolve().parents[2]


def test_migrations_upgrade_head_matches_models(
    settings: Settings, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``alembic upgrade head`` on an empty PostgreSQL database must produce exactly the
    schema the models declare, and the chain must have a single head."""
    reset_postgres_schema(settings.database_url)
    monkeypatch.setenv("DATABASE_URL", settings.database_url)
    monkeypatch.setenv("ENVIRONMENT", "test")
    reset_settings_cache()
    try:
        config = Config(str(REPO_ROOT / "alembic.ini"))
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"migrations do not match the models on PostgreSQL: {exc}")
        from sqlalchemy import create_engine

        engine = create_engine(settings.database_url)
        try:
            with engine.connect() as connection:
                versions = connection.execute(text("SELECT version_num FROM alembic_version")).all()
        finally:
            engine.dispose()
        assert len(versions) == 1
    finally:
        reset_settings_cache()
        reset_postgres_schema(settings.database_url)


def test_job_claim_skips_rows_locked_by_another_worker(
    client, email_outbox, monkeypatch: pytest.MonkeyPatch, settings: Settings
) -> None:
    """Two workers must never claim the same job: a row held under ``FOR UPDATE`` by one
    session is invisible to ``FOR UPDATE SKIP LOCKED`` in another."""
    job_id, _workspace_id = _queued_upload(client, email_outbox, monkeypatch)
    factory = inspection_session_factory()

    with factory() as holder:
        locked = holder.scalar(
            select(ProcessingJob).where(ProcessingJob.id == job_id).with_for_update()
        )
        assert locked is not None and locked.state == JobState.QUEUED

        claimed, reason = _claim_job(job_id, worker_id="worker-b", settings=settings)
        assert claimed is None
        assert reason == "busy"  # the row exists but is held by another session
        holder.rollback()

    claimed, reason = _claim_job(job_id, worker_id="worker-b", settings=settings)
    assert claimed is not None and claimed.job_id == job_id
    assert reason == "claimed"

    with factory() as db:
        job = db.get(ProcessingJob, job_id)
        assert job is not None
        assert job.state == JobState.RUNNING
        assert job.locked_by == "worker-b"
