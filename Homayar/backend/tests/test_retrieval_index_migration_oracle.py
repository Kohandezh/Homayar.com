def _assert_head_shape(name: str) -> dict:
    shape = _shape(name)
    assert shape["columns"] == {
        column: (
            PG_TYPES[kind],
            length if kind == "varchar" else None,
            "YES" if nullable else "NO",
            None,
        )
        for column, (kind, length, nullable) in COLUMNS[name].items()
    }
    constraints = shape["constraints"]
    assert {kind for kind, _ in constraints.values()} == {"p", "f", "c", "u"}
    assert {key for key, (kind, _) in constraints.items() if kind == "c"} == set(CHECKS[name])
    for check, sql in CHECKS[name].items():
        for column in set(re.findall(r"[a-z_]+", sql)) - {"length"}:
            assert column in constraints[check][1], (check, column)
    assert [key for key, (kind, _) in constraints.items() if kind == "p"] == [f"{name}_pkey"]
    assert sorted(definition for kind, definition in constraints.values() if kind == "f") == sorted(
        f"FOREIGN KEY ({column}) REFERENCES {target.split('.')[0]}(id) ON DELETE {action}"
        for column, target, action in FOREIGN_KEYS[name]
    )
    ((unique_name, columns),) = UNIQUES[name].items()
    assert {key: value for key, value in constraints.items() if value[0] == "u"} == {
        unique_name: ("u", f"UNIQUE ({', '.join(columns)})")
    }

    indexes = shape["indexes"]
    assert {index for index, definition in indexes.items() if " UNIQUE " in definition} == {
        f"{name}_pkey",
        unique_name,
    }
    for index, columns in NAMED_INDEXES[name].items():
        expected = f"CREATE INDEX {index} ON public.{name} USING btree ({', '.join(columns)})"
        if index == LIVE_INDEX:
            expected += " WHERE (superseded_at IS NULL)"
        assert indexes.get(index) == expected, index
    single = {
        definition.rsplit("(", 1)[1].rstrip(")")
        for index, definition in indexes.items()
        if " UNIQUE " not in definition and index not in NAMED_INDEXES[name] and index != FTS_INDEX
    }
    assert single == INDEXED_COLUMNS[name]
    for index, definition in indexes.items():
        if " UNIQUE " in definition or index in NAMED_INDEXES[name] or index == FTS_INDEX:
            continue
        assert definition.startswith(f"CREATE INDEX {index} ON public.{name} USING btree ("), index
    if name == ENTRIES:
        assert re.fullmatch(FTS_DEFINITION, indexes.get(FTS_INDEX, "")), indexes.get(FTS_INDEX)
    else:
        assert FTS_INDEX not in indexes

    ((policy_name, policy),) = shape["policies"].items()
    permissive, roles, command_name, using, check = policy
    assert (policy_name, permissive, roles, command_name) == (
        POLICY_NAME,
        "PERMISSIVE",
        "{public}",
        "ALL",
    )
    assert using == check
    assert "homayar.workspace_id" in using
    assert "share" not in using and "service" not in using
    assert shape["rls"] == [(True, True)]
    assert sorted(kind for grantee, kind in shape["grants"] if grantee == APP_ROLE) == GRANTS[name]
    assert shape["triggers"] == []
    return shape


