def _shape(name: str) -> dict:
    with inspection_session_factory()() as db:
        columns = db.execute(
            text(
                "SELECT column_name, data_type, character_maximum_length, is_nullable, "
                "column_default FROM information_schema.columns "
                "WHERE table_schema = 'public' AND table_name = :t"
            ),
            {"t": name},
        ).all()
        constraints = db.execute(
            text(
                "SELECT conname, contype::text, pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE conrelid = to_regclass(:t)"
            ),
            {"t": f"public.{name}"},
        ).all()
        indexes = db.execute(
            text("SELECT indexname, indexdef FROM pg_indexes WHERE tablename = :t"), {"t": name}
        ).all()
        policies = db.execute(
            text(
                "SELECT policyname, permissive, roles::text, cmd, qual, with_check "
                "FROM pg_policies WHERE tablename = :t"
            ),
            {"t": name},
        ).all()
        flags = db.execute(
            text(
                "SELECT relrowsecurity, relforcerowsecurity FROM pg_class "
                "WHERE oid = to_regclass(:t)"
            ),
            {"t": f"public.{name}"},
        ).all()
        grants = db.execute(
            text(
                "SELECT grantee::text, privilege_type::text "
                "FROM information_schema.role_table_grants "
                "WHERE table_schema = 'public' AND table_name = :t"
            ),
            {"t": name},
        ).all()
        triggers = db.execute(
            text(
                "SELECT tgname FROM pg_trigger WHERE tgrelid = to_regclass(:t) AND NOT tgisinternal"
            ),
            {"t": f"public.{name}"},
        ).all()
    return {
        "columns": {column: tuple(rest) for column, *rest in columns},
        "constraints": {conname: (kind, definition) for conname, kind, definition in constraints},
        "indexes": dict(indexes),
        "policies": {policy: tuple(rest) for policy, *rest in policies},
        "rls": [tuple(row) for row in flags],
        "grants": sorted(tuple(row) for row in grants),
        "triggers": sorted(row[0] for row in triggers),
    }


