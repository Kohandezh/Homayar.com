def _orm_kind(column) -> str:
    column_type = column.type
    if isinstance(column_type, LargeBinary):
        return "binary"
    if isinstance(column_type, Text):
        return "text"
    if isinstance(column_type, String):
        return "varchar"
    if isinstance(column_type, DateTime):
        return "datetime" if column_type.timezone else "naive-datetime"
    if isinstance(column_type, Integer):
        return "integer"
    return type(column_type).__name__


def _orm_keys(table: Table) -> set[tuple[str, str, str]]:
    keys = set()
    for constraint in table.foreign_key_constraints:
        assert len(constraint.elements) == 1, constraint.name
        (element,) = constraint.elements
        keys.add(
            (element.parent.name, element.target_fullname, (constraint.ondelete or "").upper())
        )
    return keys


def _orm_uniques(table: Table) -> dict[str, tuple[str, ...]]:
    found = {
        constraint.name: tuple(column.name for column in constraint.columns)
        for constraint in table.constraints
        if isinstance(constraint, UniqueConstraint)
    }
    found.update(
        {
            index.name: tuple(column.name for column in index.columns)
            for index in table.indexes
            if index.unique
        }
    )
    found.update(
        {f"column:{column.name}": (column.name,) for column in table.columns if column.unique}
    )
    return found


def _orm_checks(table: Table) -> dict[str, str]:
    return {
        constraint.name: str(constraint.sqltext)
        for constraint in table.constraints
        if constraint.name and constraint.name.startswith("ck_")
    }


