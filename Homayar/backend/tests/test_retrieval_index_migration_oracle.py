class _Database:
    """A transcript chain (revision, two segments, a text view, two view segments)."""

    def __init__(self, tenant: dict, label: str, meeting_id: str | None = None) -> None:
        self.postgres = _on_postgres()
        self.workspace_id = tenant["workspace_id"]
        self.user_id = tenant["user_id"]
        self.texts = TEXTS
        with inspection_session_factory()() as db:
            current = meeting_id is None
            if meeting_id is None:
                meeting = Meeting(
                    workspace_id=self.workspace_id,
                    created_by_user_id=self.user_id,
                    title=f"Indexed call {label}",
                )
                db.add(meeting)
                db.flush()
                meeting_id = meeting.id
            highest = db.scalar(
                select(func.max(TranscriptRevision.revision_number)).where(
                    TranscriptRevision.meeting_id == meeting_id
                )
            )
            revision = TranscriptRevision(
                workspace_id=self.workspace_id,
                meeting_id=meeting_id,
                revision_number=(highest or 0) + 1,
                source=TranscriptSource.ASR,
                reason="processing",
                language="fa",
                segment_count=len(TEXTS),
                is_current=current,
            )
            db.add(revision)
            db.flush()
            segments = []
            for position, value in enumerate(TEXTS):
                segment = TranscriptSegment(
                    workspace_id=self.workspace_id,
                    meeting_id=meeting_id,
                    revision_id=revision.id,
                    sequence=position,
                    speaker_key=f"speaker_{position}",
                    start_ms=position * 5000,
                    end_ms=position * 5000 + 4000,
                    text=value,
                )
                db.add(segment)
                segments.append(segment)
            db.flush()
            view = TranscriptTextView(
                workspace_id=self.workspace_id,
                meeting_id=meeting_id,
                revision_id=revision.id,
                input_view="original",
                language="fa",
                normalizer_version="speech-normalizer/1",
                extractor_version="entities/1",
                detector_version="pii/1",
                view_digest=_sha(f"{label}-{revision.id}"),
                reference_at=NOW,
                timezone="Asia/Tehran",
                state=StageState.COMPLETED,
                segment_count=len(TEXTS),
                entity_count=0,
            )
            db.add(view)
            db.flush()
            view_segments = []
            for position, value in enumerate(TEXTS):
                view_segment = TextViewSegment(
                    workspace_id=self.workspace_id,
                    meeting_id=meeting_id,
                    view_id=view.id,
                    segment_id=segments[position].id,
                    sequence=position,
                    text=value,
                    entity_count=0,
                )
                db.add(view_segment)
                view_segments.append(view_segment)
            db.flush()
            self.meeting_id = meeting_id
            self.revision_id = revision.id
            self.revision_number = revision.revision_number
            self.view_id = view.id
            self.segment_ids = [segment.id for segment in segments]
            self.view_segment_ids = [view_segment.id for view_segment in view_segments]
            db.commit()

    def table(self, name: str) -> Table:
        return _table(name)

    def run(self, statement) -> None:
        with inspection_session_factory()() as db:
            db.execute(statement)
            db.commit()

    def refuse(self, statement, pattern: str) -> None:
        with inspection_session_factory()() as db:
            with pytest.raises(DBAPIError, match=pattern):
                db.execute(statement)
            db.rollback()


