def _allow(target, name: str, values: dict[str, object]) -> str:
    target.run(insert(target.table(name)).values(values))
    return str(values["id"])


def _new_entry(target, position: int = 0, **extra: object) -> str:
    return _allow(target, ENTRIES, _entry(target, position, **extra))


def _unique_pattern(target, name: str, constraint: str) -> str:
    if target.postgres:
        return rf"\b{constraint}\b"
    columns = UNIQUES[name][constraint]
    return re.escape(", ".join(f"{name}.{column}" for column in columns))


def _deny(target, name: str, values: dict[str, object], pattern: str) -> None:
    target.refuse(insert(target.table(name)).values(values), pattern)


def _deny_check(target, name: str, values: dict[str, object], constraint: str) -> None:
    _deny(target, name, values, rf"\b{constraint}\b")


def _deny_null(target, name: str, values: dict[str, object], column: str) -> None:
    _deny(
        target,
        name,
        values,
        rf"NOT NULL constraint failed: {name}\.{column}\b|null value in column \"{column}\"",
    )


def _deny_too_long(target, name: str, values: dict[str, object], constraint: str) -> None:
    _deny(target, name, values, rf"\b{constraint}\b|value too long")


