def _vector(dimensions: int, extra: int = 0) -> bytes:
    packed = struct.pack(f"<{dimensions}f", *(((index % 7) - 3) / 4 for index in range(dimensions)))
    if extra < 0:
        return packed[:extra]
    return packed + b"\x00\xff" * (extra // 2) + b"\x00" * (extra % 2)


