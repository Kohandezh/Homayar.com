def _pg_columns(name: str) -> dict[str, tuple]:
    return {
        column: (PG_TYPES[kind], length if kind == "varchar" else None, "YES" if nullable else "NO")
        for column, (kind, length, nullable) in COLUMNS[name].items()
    }


def _pg_list(columns: tuple[str, ...]) -> str:
    return ", ".join(_scalar("SELECT quote_ident(:c)", c=column) for column in columns)


def _pg_key(columns: tuple[str, ...], targets: tuple[str, ...], action: str) -> str:
    table = targets[0].split(".")[0]
    referred = _pg_list(tuple(target.split(".")[1] for target in targets))
    return f"FOREIGN KEY ({_pg_list(columns)}) REFERENCES {table}({referred}) ON DELETE {action}"


def _assert_head_shape(name: str) -> dict:
    shape = _shape(name)
    assert shape["columns"] == _pg_columns(name), name
    constraints = shape["constraints"]
    assert {conname for conname, (kind, _) in constraints.items() if kind == "c"} == CHECKS[name]
    assert [conname for conname, (kind, _) in constraints.items() if kind == "p"] == [
        f"{name}_pkey"
    ]
    keys = _orm_keys(_table(name))
    assert keys == FOREIGN_KEYS[name], keys
    assert sorted(definition for kind, definition in constraints.values() if kind == "f") == sorted(
        _pg_key(*key) for key in keys
    )
    targets = {columns: (target, action) for columns, target, action in keys}
    for columns, key_name in NAMED_KEYS[name].items():
        assert constraints.get(key_name) == ("f", _pg_key(columns, *targets[columns])), key_name

    indexes = shape["indexes"]
    unique = {
        index for index, definition in indexes.items() if definition.startswith("CREATE UNIQUE")
    }
    assert unique == {f"{name}_pkey", *UNIQUE_KEYS[name]}
    for unique_name, columns in UNIQUE_KEYS[name].items():
        assert indexes[unique_name] == (
            f"CREATE UNIQUE INDEX {unique_name} ON public.{name} USING btree ({_pg_list(columns)})"
        )
    for index_name, columns in NAMED_INDEXES[name].items():
        assert indexes.get(index_name) == (
            f"CREATE INDEX {index_name} ON public.{name} USING btree ({_pg_list(columns)})"
        )
    for indexed in INDEXED_COLUMNS[name]:
        assert any(
            definition.startswith("CREATE INDEX ")
            and definition.endswith(f" ON public.{name} USING btree ({_pg_list(indexed)})")
            for definition in indexes.values()
        ), indexed

    ((policy_name, policy),) = shape["policies"].items()
    permissive, roles, command_name, using, check = policy
    assert (policy_name, permissive, roles, command_name) == (
        POLICY_NAME,
        "PERMISSIVE",
        "{public}",
        "ALL",
    )
    assert using == check
    assert "homayar.workspace_id" in using
    assert "share" not in using and "service" not in using
    assert shape["rls"] == [(True, True)]
    assert shape["grants"] == GRANTS[name]
    return shape


