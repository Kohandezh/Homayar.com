def _names(target, constraint: str) -> str:
    if not target.postgres:
        if constraint in SQLITE_UNIQUE:
            table, columns = SQLITE_UNIQUE[constraint]
            return re.escape(", ".join(f"{table}.{column}" for column in columns))
        if constraint.startswith("fk_"):
            return "FOREIGN KEY constraint failed"
    return rf"\b{constraint}\b"


def _deny(target, name: str, values: dict[str, object], constraint: str, *also: str) -> None:
    names = (constraint, *also) if target.postgres else (constraint,)
    target.refuse(
        insert(target.table(name)).values(values),
        "|".join(_names(target, each) for each in names),
    )


def _deny_null(target, name: str, values: dict[str, object], column: str) -> None:
    target.refuse(
        insert(target.table(name)).values(values),
        rf"{name}\.{column}\b|null value in column \"{column}\"",
    )


def _allow(target, name: str, values: dict[str, object]) -> str:
    target.run(insert(target.table(name)).values(values))
    return str(values["id"])


