def _table(name: str) -> Table:
    assert name in Base.metadata.tables, f"the ORM declares no {name} table"
    return Base.metadata.tables[name]


def _count(name: str, **where: str) -> int:
    table = _table(name)
    statement = select(func.count()).select_from(table)
    for column, value in where.items():
        statement = statement.where(table.c[column] == value)
    with inspection_session_factory()() as db:
        return db.scalar(statement)


def _ids(name: str) -> set[str]:
    table = _table(name)
    with inspection_session_factory()() as db:
        return set(db.execute(select(table.c.id)).scalars())


def _snapshot(name: str, row_id: str) -> dict[str, object]:
    table = _table(name)
    with inspection_session_factory()() as db:
        return dict(db.execute(select(table).where(table.c.id == row_id)).mappings().one())


