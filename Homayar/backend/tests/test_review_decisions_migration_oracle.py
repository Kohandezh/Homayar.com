def _ddl_digest(name: str, dialect) -> tuple[str, str]:
    table = _table(name)
    parts = [str(CreateTable(table).compile(dialect=dialect)).strip()]
    parts += sorted(
        str(CreateIndex(index).compile(dialect=dialect)).strip()
        for index in table.indexes
        if index.name != ITEM_RESULT_INDEX
    )
    ddl = "\n".join(parts)
    return hashlib.sha256(ddl.encode()).hexdigest(), ddl


