def _reflect(connection, name: str) -> dict:
    inspector = inspect(connection)
    return {
        "columns": [
            (column["name"], str(column["type"]), column["nullable"])
            for column in inspector.get_columns(name)
        ],
        "primary_key": inspector.get_pk_constraint(name)["constrained_columns"],
        "foreign_keys": sorted(
            (
                key["name"] or "",
                tuple(key["constrained_columns"]),
                key["referred_table"],
                tuple(key["referred_columns"]),
                (key["options"].get("ondelete") or "").upper(),
            )
            for key in inspector.get_foreign_keys(name)
        ),
        "unique": sorted(
            (unique["name"] or "", tuple(unique["column_names"]))
            for unique in inspector.get_unique_constraints(name)
        ),
        "checks": sorted(
            (check["name"] or "", check["sqltext"])
            for check in inspector.get_check_constraints(name)
        ),
        "indexes": sorted(
            (index["name"], tuple(index["column_names"]), bool(index["unique"]))
            for index in inspector.get_indexes(name)
        ),
    }


def _sqlite_objects(connection) -> list[tuple]:
    rows = connection.exec_driver_sql(
        "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE tbl_name <> 'alembic_version'"
    )
    return sorted(tuple(row) for row in rows)


def test_on_sqlite_the_migration_builds_the_orm_schema_and_its_downgrade_removes_only_it(
    tmp_path, monkeypatch
):
    revision = _new_revision()
    url = f"sqlite:///{tmp_path / 'review-decisions.db'}"
    engine = create_engine(url)
    try:
        with engine.begin() as connection:
            Base.metadata.create_all(connection)
            orm = {name: _reflect(connection, name) for name in (*TABLES, ITEMS)}
            for name in TABLES:
                _table(name).drop(connection)
            connection.exec_driver_sql(f"DROP INDEX {ITEM_RESULT_INDEX}")
            # The five HOM-75 calibration tables, the three HOM-76 appeal tables and
            # the HOM-77 coaching tasks of the head already exist (``create_all``);
            # drop them, so the head's own migrations can build them again below.
            for name in (
                "coaching_tasks",
                "calibration_batches",
                "calibration_examples",
                "calibration_participants",
                "calibration_answers",
                "calibration_adjudications",
                "review_appeal_results",
                "review_appeal_criteria",
                "review_appeals",
                "retrieval_embeddings",
                "retrieval_entries",
            ):
                Base.metadata.tables[name].drop(connection)
            # HOM-133 adds ``action_items.kind``; take it out, so the head's own
            # migration adds it again below.
            remove_action_item_kind(connection)
            # HOM-128 adds the federation mapping table and two columns; take
            # them out, so the head's own migration adds them again below.
            remove_federation_group_mappings(connection)
            # HOM-129 adds the MFA and break-glass schema; take it out too.
            remove_privileged_mfa_schema(connection)
            # HOM-135 adds the action proposal tables; take them out too.
            remove_action_proposals(connection)
            # HOM-134 adds the product alert tables; take them out too.
            remove_product_alerts(connection)
            before = _sqlite_objects(connection)
        assert (ITEM_RESULT_INDEX, ("id", "scorecard_result_id"), True) in orm[ITEMS]["indexes"]
        assert sorted(name for name, _ in orm[DECISIONS]["checks"]) == sorted(DECISION_CHECKS)
        assert sorted(name for name, _ in orm[RESULTS]["checks"]) == sorted(RESULT_CHECKS)

        config = _alembic(monkeypatch, url)
        command.stamp(config, revision.down_revision)
        command.upgrade(config, revision.revision)
        with engine.connect() as connection:
            for name in (*TABLES, ITEMS):
                assert _reflect(connection, name) == orm[name], name
            unchanged = [
                row
                for row in _sqlite_objects(connection)
                if row[2] not in TABLES and row[1] != ITEM_RESULT_INDEX
            ]
            assert unchanged == before
        # The head's own migrations (HOM-75 builds the calibration tables, HOM-76
        # the appeal tables, HOM-133 the action item kind, HOM-77 the coaching tasks)
        # complete the schema, so ``alembic check`` passes.
        command.upgrade(config, "head")
        _check(config)

        scratch = _Scratch(engine)
        for rules in CHECK_RULES:
            rules(scratch)

        # Back below this revision: the head's tables, this one's tables and the item
        # index go with the downgrade.
        command.downgrade(config, revision.down_revision)
        with engine.connect() as connection:
            version = connection.exec_driver_sql("SELECT version_num FROM alembic_version")
            assert version.scalar() == revision.down_revision
            assert _sqlite_objects(connection) == before
    finally:
        engine.dispose()
        reset_settings_cache()


def _shape(name: str) -> dict:
    with inspection_session_factory()() as db:
        columns = db.execute(
            text(
                "SELECT column_name, data_type, character_maximum_length, is_nullable "
                "FROM information_schema.columns "
                "WHERE table_schema = 'public' AND table_name = :t"
            ),
            {"t": name},
        ).all()
        constraints = db.execute(
            text(
                "SELECT conname, contype::text, pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE conrelid = to_regclass(:t)"
            ),
            {"t": f"public.{name}"},
        ).all()
        indexes = db.execute(
            text("SELECT indexname, indexdef FROM pg_indexes WHERE tablename = :t"), {"t": name}
        ).all()
        policies = db.execute(
            text(
                "SELECT policyname, permissive, roles::text, cmd, qual, with_check "
                "FROM pg_policies WHERE tablename = :t"
            ),
            {"t": name},
        ).all()
        flags = db.execute(
            text(
                "SELECT relrowsecurity, relforcerowsecurity FROM pg_class "
                "WHERE oid = to_regclass(:t)"
            ),
            {"t": f"public.{name}"},
        ).all()
        grants = db.execute(
            text(
                "SELECT privilege_type FROM information_schema.role_table_grants "
                "WHERE table_schema = 'public' AND table_name = :t AND grantee = :r"
            ),
            {"t": name, "r": APP_ROLE},
        ).all()
    return {
        "columns": {column: tuple(rest) for column, *rest in columns},
        "constraints": {conname: (kind, definition) for conname, kind, definition in constraints},
        "indexes": dict(indexes),
        "policies": {policy: tuple(rest) for policy, *rest in policies},
        "rls": [tuple(row) for row in flags],
        "grants": sorted(row[0] for row in grants),
    }


