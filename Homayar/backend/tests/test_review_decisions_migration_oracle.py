def _assert_orm_type(name: str, column, kind: str, length: int | None) -> None:
    column_type = column.type
    if kind == "varchar":
        assert isinstance(column_type, String) and not isinstance(column_type, Text), name
        assert column_type.length == length, name
    elif kind == "text":
        assert isinstance(column_type, Text), name
    elif kind == "json":
        assert column_type.__class__.__name__ == "JSON", name
    elif kind == "datetime":
        assert isinstance(column_type, DateTime) and column_type.timezone, name
    elif kind == "integer":
        assert isinstance(column_type, Integer), name
    elif kind == "boolean":
        assert isinstance(column_type, Boolean), name


def _unique_keys(table: Table) -> dict[str, tuple[str, ...]]:
    found = {
        constraint.name: tuple(column.name for column in constraint.columns)
        for constraint in table.constraints
        if isinstance(constraint, UniqueConstraint)
    }
    found.update(
        {
            index.name: tuple(column.name for column in index.columns)
            for index in table.indexes
            if index.unique
        }
    )
    return found


def _assert_orm_table(name: str, model_name: str) -> Table:
    table = _table(name)
    assert _model(model_name).__table__ is table
    assert set(table.c.keys()) == set(COLUMNS[name])
    for column_name, (kind, length, nullable) in COLUMNS[name].items():
        _assert_orm_type(column_name, table.c[column_name], kind, length)
        assert table.c[column_name].nullable is nullable, column_name
    assert [column.name for column in table.primary_key] == ["id"]

    keys = table.foreign_key_constraints
    assert {
        (
            tuple(key.column_keys),
            tuple(element.target_fullname for element in key.elements),
            (key.ondelete or "").upper(),
        )
        for key in keys
    } == FOREIGN_KEYS[name]
    named = {tuple(key.column_keys): key.name for key in keys if len(key.column_keys) > 1}
    assert named == NAMED_KEYS[name]

    unique_name, unique_columns = UNIQUE_KEYS[name]
    assert _unique_keys(table) == {unique_name: unique_columns}

    indexes = {index.name: index for index in table.indexes if not index.unique}
    index_name, index_columns = NAMED_INDEXES[name]
    assert index_name in indexes
    assert tuple(column.name for column in indexes[index_name].columns) == index_columns
    columns = {tuple(column.name for column in index.columns) for index in indexes.values()}
    for indexed in INDEXED_COLUMNS[name]:
        assert indexed in columns, indexed
    return table


