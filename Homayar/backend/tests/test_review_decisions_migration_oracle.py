def _pg_columns(name: str) -> dict[str, tuple]:
    return {
        column: (PG_TYPES[kind], length if kind == "varchar" else None, "YES" if nullable else "NO")
        for column, (kind, length, nullable) in COLUMNS[name].items()
    }


def _pg_key(columns: tuple[str, ...], targets: tuple[str, ...], action: str) -> str:
    table = targets[0].split(".")[0]
    referred = ", ".join(target.split(".")[1] for target in targets)
    return f"FOREIGN KEY ({', '.join(columns)}) REFERENCES {table}({referred}) ON DELETE {action}"


def _assert_head_shape(name: str) -> dict:
    shape = _shape(name)
    assert shape["columns"] == _pg_columns(name)
    constraints = shape["constraints"]
    expected_checks = set(DECISION_CHECKS) if name == DECISIONS else set(RESULT_CHECKS)
    assert {conname for conname, (kind, _) in constraints.items() if kind == "c"} == expected_checks
    assert [conname for conname, (kind, _) in constraints.items() if kind == "p"] == [
        f"{name}_pkey"
    ]
    assert sorted(definition for kind, definition in constraints.values() if kind == "f") == sorted(
        _pg_key(*key) for key in FOREIGN_KEYS[name]
    )
    for columns, targets, action in FOREIGN_KEYS[name]:
        if len(columns) > 1:
            assert constraints[NAMED_KEYS[name][columns]] == (
                "f",
                _pg_key(columns, targets, action),
            )

    indexes = shape["indexes"]
    unique_name, unique_columns = UNIQUE_KEYS[name]
    assert indexes[unique_name] == (
        f"CREATE UNIQUE INDEX {unique_name} ON public.{name} USING btree "
        f"({', '.join(unique_columns)})"
    )
    index_name, index_columns = NAMED_INDEXES[name]
    assert indexes[index_name] == (
        f"CREATE INDEX {index_name} ON public.{name} USING btree ({', '.join(index_columns)})"
    )
    for indexed in INDEXED_COLUMNS[name]:
        assert any(
            definition.startswith("CREATE INDEX ")
            and definition.endswith(f" ON public.{name} USING btree ({', '.join(indexed)})")
            for definition in indexes.values()
        ), indexed

    ((policy_name, policy),) = shape["policies"].items()
    permissive, roles, command_name, using, check = policy
    assert (policy_name, permissive, roles, command_name) == (
        POLICY_NAME,
        "PERMISSIVE",
        "{public}",
        "ALL",
    )
    assert using == check
    assert "homayar.workspace_id" in using
    assert "share" not in using and "service" not in using
    assert shape["rls"] == [(True, True)]
    assert shape["grants"] == GRANTS[name]
    return shape


