def _fields(status: str, **extra: object) -> dict[str, object]:
    return {"status": status, **STATUS_FIELDS.get(status, {}), **extra}


def _names(target, constraint: str) -> str:
    if not target.postgres:
        # SQLite names the columns of a broken unique index, and no foreign key.  Each
        # foreign key deny names a workspace and a meeting that exist, so only the
        # composite key can refuse it.
        if constraint == ACTIVE_INDEX:
            return re.escape(f"{TABLE}.workspace_id, {TABLE}.meeting_id")
        if constraint.startswith("fk_"):
            return "FOREIGN KEY constraint failed"
    return rf"\b{constraint}\b"


def _refused(target, values: dict[str, object], constraint: str) -> None:
    """The insert fails on ``constraint``; each deny breaks that rule alone."""
    target.refuse(insert(target.table()).values(values), _names(target, constraint))


def _added(target, values: dict[str, object]) -> str:
    target.run(insert(target.table()).values(values))
    return str(values["id"])


