def _reflect(connection) -> dict:
    inspector = inspect(connection)
    return {
        "columns": {
            column["name"]: (str(column["type"]), column["nullable"])
            for column in inspector.get_columns(TABLE)
        },
        "primary_key": inspector.get_pk_constraint(TABLE)["constrained_columns"],
        "foreign_keys": sorted(
            (
                key["name"] or "",
                tuple(key["constrained_columns"]),
                tuple(f"{key['referred_table']}.{column}" for column in key["referred_columns"]),
                (key["options"].get("ondelete") or "").upper(),
            )
            for key in inspector.get_foreign_keys(TABLE)
        ),
        "unique": sorted(
            unique["name"] or "" for unique in inspector.get_unique_constraints(TABLE)
        ),
        "checks": sorted(check["name"] or "" for check in inspector.get_check_constraints(TABLE)),
        "indexes": {
            index["name"]: (
                tuple(index["column_names"]),
                bool(index["unique"]),
                "sqlite_where" in index.get("dialect_options", {}),
            )
            for index in inspector.get_indexes(TABLE)
        },
    }


def _sqlite_objects(connection) -> list[tuple]:
    rows = connection.exec_driver_sql(
        "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE tbl_name <> 'alembic_version'"
    )
    return sorted(tuple(row) for row in rows)


