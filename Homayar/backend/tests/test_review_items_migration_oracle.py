def test_the_orm_model_declares_the_designed_table():
    table = _model().__table__
    assert table is _table()
    assert set(table.c.keys()) == {*LENGTHS, *DATETIMES, "source_details", "revision"}
    for name, length in LENGTHS.items():
        assert table.c[name].type.length == length, name
    for name in DATETIMES:
        assert isinstance(table.c[name].type, DateTime) and table.c[name].type.timezone, name
    assert isinstance(table.c.revision.type, Integer)
    assert table.c.source_details.type.__class__.__name__ == "JSON"
    assert [column.name for column in table.primary_key] == ["id"]
    assert {column.name for column in table.columns if column.nullable} == NULLABLE

    keys = table.foreign_key_constraints
    assert {
        (
            tuple(key.column_keys),
            tuple(element.target_fullname for element in key.elements),
            (key.ondelete or "").upper(),
        )
        for key in keys
    } == FOREIGN_KEYS
    assert [key.name for key in keys if tuple(key.column_keys) == RESULT_COLUMNS] == [RESULT_KEY]
    names = {constraint.name for constraint in table.constraints if constraint.name}
    assert {name for name in names if name.startswith("ck_")} == set(CHECKS)
    assert [c for c in table.constraints if isinstance(c, UniqueConstraint)] == []

    indexes = {index.name: index for index in table.indexes}
    assert {
        name: (tuple(column.name for column in index.columns), bool(index.unique))
        for name, index in indexes.items()
    } == INDEXES
    for dialect in ("sqlite", "postgresql"):
        assert indexes[ACTIVE_INDEX].dialect_options[dialect]["where"] is not None, dialect


