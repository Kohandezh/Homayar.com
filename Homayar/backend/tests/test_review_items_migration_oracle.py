def _assert_scorecard_result_scope(tenant: dict, other: dict) -> None:
    """An item points only at a result of its own meeting (SPEC criterion 4).

    ``other`` is another workspace.
    """
    ours, theirs = _Database(tenant), _Database(other)
    x = _parents(tenant, key="meeting_x")
    y = _parents(tenant, key="meeting_y")
    elsewhere = _parents(other, key="elsewhere")
    result_x, result_y, result_elsewhere = [
        _add(ScorecardResultRecord, _result(parents)) for parents in (x, y, elsewhere)
    ]
    meeting = y["meeting_id"]
    for result_id in (result_x, result_elsewhere, str(uuid.uuid4())):
        _refused(ours, _item(ours, meeting, scorecard_result_id=result_id), RESULT_KEY)
    # Another workspace's meeting and result under this workspace's id.
    _refused(
        ours,
        _item(ours, elsewhere["meeting_id"], scorecard_result_id=result_elsewhere),
        RESULT_KEY,
    )
    _added(ours, _item(ours, meeting, scorecard_result_id=result_y))
    _added(ours, _item(ours, meeting, **_fields("completed"), scorecard_result_id=None))
    _added(theirs, _item(theirs, elsewhere["meeting_id"], scorecard_result_id=result_elsewhere))


