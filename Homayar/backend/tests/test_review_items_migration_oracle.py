def _assert_status_and_source_rules(target) -> None:
    for status in ("done", "Open", "in-review", "inreview", "open ", ""):
        _refused(target, _item(target, status=status), "ck_review_items_status")
    for status in STATUSES:
        _added(target, _item(target, **_fields(status)))

    for source in ("auto", "Manual", "samples", ""):
        _refused(target, _item(target, source=source), "ck_review_items_source")
    for source in SOURCES:
        _added(target, _item(target, source=source))


def _assert_cancel_reason_rules(target) -> None:
    for reason in ("spam", "Duplicate", "out-of-scope", "out of scope", ""):
        _refused(
            target,
            _item(target, **_fields("cancelled", cancel_reason=reason)),
            "ck_review_items_cancel_reason",
        )
    for reason in CANCEL_REASONS:
        _added(target, _item(target, **_fields("cancelled", cancel_reason=reason)))


def _assert_revision_rules(target) -> None:
    for revision in (0, -1):
        _refused(target, _item(target, revision=revision), "ck_review_items_revision")
    for revision in (1, 2):
        _added(target, _item(target, revision=revision))


def _assert_open_fields_rule(target) -> None:
    rule = "ck_review_items_open_fields"
    for column, value in (
        ("cancel_reason", "duplicate"),
        ("started_at", NOW),
        ("completed_at", NOW),
        ("cancelled_at", NOW),
    ):
        _refused(target, _item(target, **{column: value}), rule)
    _added(target, _item(target, cancel_reason=None))


def _assert_in_review_fields_rule(target) -> None:
    rule = "ck_review_items_in_review_fields"
    _refused(target, _item(target, status="in_review"), rule)
    for column, value in (("completed_at", NOW), ("cancelled_at", NOW), ("cancel_reason", "other")):
        _refused(target, _item(target, **_fields("in_review", **{column: value})), rule)
    _added(target, _item(target, **_fields("in_review")))


def _assert_completed_fields_rule(target) -> None:
    rule = "ck_review_items_completed_fields"
    for column in ("completed_at", "started_at"):
        _refused(target, _item(target, **_fields("completed", **{column: None})), rule)
    for column, value in (("cancelled_at", NOW), ("cancel_reason", "other")):
        _refused(target, _item(target, **_fields("completed", **{column: value})), rule)
    _added(target, _item(target, **_fields("completed")))


def _assert_cancelled_fields_rule(target) -> None:
    rule = "ck_review_items_cancelled_fields"
    for column in ("cancel_reason", "cancelled_at"):
        _refused(target, _item(target, **_fields("cancelled", **{column: None})), rule)
    _refused(target, _item(target, **_fields("cancelled", completed_at=NOW)), rule)
    _added(target, _item(target, **_fields("cancelled")))
    # An item cancelled during its review keeps its start time.
    _added(target, _item(target, **_fields("cancelled", started_at=NOW)))


def _assert_one_active_item_per_meeting(target) -> None:
    meeting = target.meeting()
    first = _added(target, _item(target, meeting))
    for status in ("open", "in_review"):
        _refused(target, _item(target, meeting, **_fields(status)), ACTIVE_INDEX)
    for status in ("completed", "cancelled"):
        _added(target, _item(target, meeting, **_fields(status)))
    _added(target, _item(target))  # another meeting's active item

    # A finished item does not block a new one.
    table = target.table()
    target.run(update(table).where(table.c.id == first).values(**_fields("completed")))
    second = _added(target, _item(target, meeting, **_fields("in_review")))
    _refused(target, _item(target, meeting), ACTIVE_INDEX)
    target.run(update(table).where(table.c.id == second).values(**_fields("cancelled")))
    _added(target, _item(target, meeting))


